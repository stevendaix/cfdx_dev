# # 01 — Requirements and Claims
#
# A requirement should be testable. A useful record is
#
# \[
# R=(ID,statement,scope,metric,criterion,evidence).
# \]
#
# ## Claim-to-evidence chain
#
# \[
# \text{requirement}\rightarrow\text{mathematical property}\rightarrow\text{implementation}\rightarrow\text{test}\rightarrow\text{artifact}\rightarrow\text{qualification}.
# \]
#
# A benchmark without a declared property is descriptive evidence, not automatically a verification claim.
#
# ## Acceptance
#
# Define the metric before execution. For an observed order,
#
# \[
# p=\frac{\log(E_1/E_2)}{\log(h_1/h_2)}.
# \]
#
# The required minimum order, error bound or conservation defect must be declared independently of the measured value.
#
# ## Traceability
#
# Every qualification row should link to a stable requirement identifier, implementation location, test or campaign identifier and retained result artifact.

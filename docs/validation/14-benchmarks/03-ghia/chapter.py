# # Ghia lid-driven cavity
#
# A square cavity has stationary walls except for a moving lid of velocity U. The flow is incompressible and closed, so net mass flux is zero and pressure has a constant null space.
#
# \[
# Re=UH/\nu.
# \]
#
# The classical Ghia, Ghia and Shin reference is used through centreline velocity profiles and vortex information.
#
# Quantities: vertical-centreline horizontal velocity, horizontal-centreline vertical velocity, primary-vortex position/strength, secondary vortices where resolved, mass imbalance.
#
# This case exercises pressure-velocity coupling, convection, diffusion, boundary conditions and recirculation.
#
# Campaign: exact Reynolds number; mesh sequence; steady-state criterion; profile interpolation; profile norm; vortex-location comparison. Passing one Reynolds number does not qualify the entire cavity population.

// Diagnostic-only: exactly the same nonlinear iterate and mass flux for the
// deferred TVD correction, predictor H/A and Rhie-Chow pressure response.
// This file never modifies the solver or its acceptance thresholds.
#include "cfdx/physics/finite_volume_transport.h"
#include <algorithm>
#include <cmath>
#include <cstddef>

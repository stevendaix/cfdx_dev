struct MomentumLinearRelaxationEvidence {
    double relaxed_true_l2 = 0.0;
    double relaxed_true_relative = 0.0;
    double original_operator_l2 = 0.0;
    double original_operator_relative = 0.0;
    double relaxation_displacement_l2 = 0.0;
    double velocity_change_linf = 0.0;
    double relaxed_true_linf = 0.0;
    double original_operator_linf = 0.0;
    std::size_t worst_original_cell = 0;
};

// For each cell, A_rel=A_original+D and b_rel=b_original+D*U_old,
// where D=(1-alpha)*diag(A_rel). Thus
//   (A_original U-b_original)=(A_rel U-b_rel)-D*(U-U_old).
// The first term is the TRUE linear-solve error; the second is the exact
// non-stationary displacement generated by under-relaxation. The original
// frozen Picard operator is not the nonlinear residual after pressure update.
inline MomentumLinearRelaxationEvidence audit_momentum_linear_relaxation(
    const ScalarEquation& relaxed,
    const cfdx::core::Vector& current,
    const cfdx::core::Vector& old,
    double alpha)
{
    const std::size_t n = relaxed.rhs.size();
    if (!(alpha > 0.0 && alpha <= 1.0) || !std::isfinite(alpha) ||
        current.size() != n || old.size() != n ||
        relaxed.matrix.n_rows() != n || relaxed.matrix.n_cols() != n ||
        relaxed.diagonal.size() != n)
        throw std::invalid_argument("linear relaxation audit: invalid sizes or alpha");
    MomentumLinearRelaxationEvidence out;
    double rhs_rel_l2 = 0.0, rhs_original_l2 = 0.0;
    const auto* row = relaxed.matrix.row_offsets_data();
    const auto* col = relaxed.matrix.columns_data();
    const auto* val = relaxed.matrix.values_data();
    for (std::size_t i=0; i<n; ++i) {
        const double added=(1.0-alpha)*relaxed.diagonal[i];
        double ax = 0.0;
        for (auto k=row[i]; k<row[i+1]; ++k)
            ax += val[k]*current(col[k]);
        const double rr=ax-relaxed.rhs(i);
        const double displacement=added*(current(i)-old(i));
        const double ro=rr-displacement;
        const double original_rhs=relaxed.rhs(i)-added*old(i);
        if (!std::isfinite(ax) || !std::isfinite(rr) || !std::isfinite(ro) ||
            !std::isfinite(original_rhs) || !std::isfinite(displacement))
            throw std::domain_error("linear relaxation audit: nonfinite result");
        out.relaxed_true_l2=std::hypot(out.relaxed_true_l2,rr);
        out.original_operator_l2=std::hypot(out.original_operator_l2,ro);
        out.relaxation_displacement_l2=std::hypot(
            out.relaxation_displacement_l2,displacement);
        rhs_rel_l2=std::hypot(rhs_rel_l2,relaxed.rhs(i));
        rhs_original_l2=std::hypot(rhs_original_l2,original_rhs);
        out.relaxed_true_linf=std::max(out.relaxed_true_linf,std::abs(rr));
        if (std::abs(ro)>out.original_operator_linf) {
            out.original_operator_linf=std::abs(ro);
            out.worst_original_cell=i;
        }
        out.velocity_change_linf=std::max(out.velocity_change_linf,
                                           std::abs(current(i)-old(i)));
    }
    out.relaxed_true_relative=rhs_rel_l2>0.0
        ? out.relaxed_true_l2/rhs_rel_l2 :
        (out.relaxed_true_l2==0.0 ? 0.0 : std::numeric_limits<double>::infinity());
    out.original_operator_relative=rhs_original_l2>0.0
        ? out.original_operator_l2/rhs_original_l2 :
        (out.original_operator_l2==0.0 ? 0.0 : std::numeric_limits<double>::infinity());
    return out;
}

// This is the actual frozen Picard assembly input: U_old and conservative
// phi_old as passed to the momentum equation, BEFORE pressure correction.
// It must never be conflated with the accepted-state flux reconstruction
// after the step. Both views are useful, but they are different iterates.
struct MomentumPicardTvdFace {
    std::size_t face = 0, owner = 0;
    long long neighbour = -1;
    double mass_flux_old = 0.0;
    double upwind_flux = 0.0;
    double selected_flux = 0.0;
    double deferred_tvd_flux = 0.0;
    // Effective (memory-filtered) deferred flux actually assembled this step;
    // identical to deferred_tvd_flux whenever the TVD defect memory is off.
    double effective_deferred_flux = 0.0;
    double memory_filter_delta = 0.0;
};
struct MomentumPicardTvdTrace {
    double high_order_fraction = 0.0;
    std::vector<MomentumPicardTvdFace> faces;
    double max_deferred_flux = 0.0;
};
inline MomentumPicardTvdTrace audit_momentum_picard_tvd_faces(
    const cfdx::core::Mesh& mesh, const FvGeometry& geometry,
    const cfdx::core::Field<double,cfdx::core::Location::FACE>& old_mass_flux,
    const cfdx::core::Field<double,cfdx::core::Location::CELL>& old_velocity_y,
    const ScalarBoundaryConditions& boundary,
    ConvectionScheme scheme, double high_order_fraction)
{
    if (old_mass_flux.size()!=mesh.n_faces() ||
        old_velocity_y.size()!=mesh.n_cells() ||
        !std::isfinite(high_order_fraction) || high_order_fraction<0.0 ||
        high_order_fraction>1.0)
        throw std::invalid_argument("Picard TVD trace: incompatible assembly inputs");
    const auto upwind=reconstruct_scalar_transport_flux(
        mesh,geometry,old_mass_flux,old_velocity_y,0.0,boundary,
        true,ConvectionScheme::UPWIND);
    const auto selected=reconstruct_scalar_transport_flux(
        mesh,geometry,old_mass_flux,old_velocity_y,0.0,boundary,
        true,scheme,nullptr,nullptr,nullptr,nullptr,high_order_fraction);
    MomentumPicardTvdTrace out;
    out.high_order_fraction=high_order_fraction;
    out.faces.reserve(mesh.n_faces());
    for (std::size_t f=0;f<mesh.n_faces();++f) {
        MomentumPicardTvdFace record;
        record.face=f;
        record.owner=mesh.ownership().owner(f);
        record.neighbour=mesh.ownership().neighbour(f);
        record.mass_flux_old=old_mass_flux(f);
        record.upwind_flux=upwind(f);
        record.selected_flux=selected(f);
        record.deferred_tvd_flux=selected(f)-upwind(f);
        record.effective_deferred_flux=record.deferred_tvd_flux;
        if (!std::isfinite(record.mass_flux_old) ||
            !std::isfinite(record.deferred_tvd_flux))
            throw std::domain_error("Picard TVD trace: nonfinite flux");
        out.max_deferred_flux=std::max(out.max_deferred_flux,
                                      std::abs(record.deferred_tvd_flux));
        out.faces.push_back(record);
    }
    return out;
}

struct MomentumSameStateFace {
    std::size_t face = 0, owner = 0;
    long long neighbour = -1;
    double mass_flux = 0.0;
    double upwind_convection = 0.0;
    double selected_convection = 0.0;
    double deferred_tvd_flux = 0.0;
    double predictor_hbya_flux = 0.0;
    double rc_relaxed_flux = 0.0;
    double rc_full_flux = 0.0;
    double conservative_flux = 0.0;
    double rc_pressure_response = 0.0;
    double pressure_relaxation_split = 0.0;
    double simplec_extra_flux = 0.0;
    double decomposition_error = 0.0;
    double internal_pressure_operator = std::numeric_limits<double>::quiet_NaN();
    double pressure_operator_error = std::numeric_limits<double>::quiet_NaN();
};

struct MomentumSameStateTrace {
    std::vector<MomentumSameStateFace> faces;
    double max_decomposition_error = 0.0;
    double max_deferred_tvd_flux = 0.0;
    double max_pressure_operator_error = 0.0;
    std::size_t max_deferred_tvd_face = 0;
};

// The predictor and the two RC fluxes MUST have been constructed from one
// frozen H/A, inverse diagonal, boundary policy and state. In particular,
// rc_full_flux uses the flux-pressure state, which can differ from the
// under-relaxed physical pressure used for the cell U correction.
// rc_pressure_response = phi_H/A - phi_RC(p_relaxed)
// pressure_split      = phi_RC(p_full) - phi_RC(p_relaxed)
// simplec_extra       = phi_authoritative - phi_RC(p_full).
// The identity phi_authoritative=phi_H/A-rc_pressure_response +
// pressure_split+simplec_extra is checked facewise. None of these terms is
// misnamed as a pure difference between RC and interpolated final velocity.
inline MomentumSameStateTrace audit_momentum_same_state_faces(
    const cfdx::core::Mesh& mesh,
    const FvGeometry& geometry,
    const cfdx::core::Field<double,cfdx::core::Location::FACE>& mass_flux,
    const cfdx::core::Field<double,cfdx::core::Location::CELL>& component,
    const ScalarBoundaryConditions& velocity_boundary,
    ConvectionScheme scheme,
    double high_order_fraction,
    const cfdx::core::Field<double,cfdx::core::Location::FACE>& predictor_hbya,
    const cfdx::core::Field<double,cfdx::core::Location::FACE>& rc_relaxed,
    const cfdx::core::Field<double,cfdx::core::Location::FACE>& rc_full,
    const cfdx::core::Field<double,cfdx::core::Location::FACE>*
        independent_pressure_operator = nullptr)
{
    if (mass_flux.size()!=mesh.n_faces() || component.size()!=mesh.n_cells() ||
        predictor_hbya.size()!=mesh.n_faces() || rc_relaxed.size()!=mesh.n_faces() ||
        rc_full.size()!=mesh.n_faces() ||
        (independent_pressure_operator && independent_pressure_operator->size()!=mesh.n_faces()) ||
        !std::isfinite(high_order_fraction) ||
        high_order_fraction<0.0 || high_order_fraction>1.0)
        throw std::invalid_argument("same-state momentum audit: mismatched fields");
    const auto first = reconstruct_scalar_transport_flux(
        mesh, geometry, mass_flux, component, 0.0, velocity_boundary,
        true, ConvectionScheme::UPWIND);
    const auto selected = reconstruct_scalar_transport_flux(
        mesh, geometry, mass_flux, component, 0.0, velocity_boundary,
        true, scheme, nullptr, nullptr, nullptr, nullptr, high_order_fraction);
    MomentumSameStateTrace out;
    out.faces.reserve(mesh.n_faces());
    for (std::size_t f=0; f<mesh.n_faces(); ++f) {
        MomentumSameStateFace record;
        record.face=f;
        record.owner=mesh.ownership().owner(f);
        record.neighbour=mesh.ownership().neighbour(f);
        record.mass_flux=mass_flux(f);
        record.upwind_convection=first(f);
        record.selected_convection=selected(f);
        record.deferred_tvd_flux=selected(f)-first(f);
        record.predictor_hbya_flux=predictor_hbya(f);
        record.rc_relaxed_flux=rc_relaxed(f);
        record.rc_full_flux=rc_full(f);
        record.conservative_flux=mass_flux(f);
        record.rc_pressure_response=predictor_hbya(f)-rc_relaxed(f);
        record.pressure_relaxation_split=rc_full(f)-rc_relaxed(f);
        record.simplec_extra_flux=mass_flux(f)-rc_full(f);
        record.decomposition_error=(record.predictor_hbya_flux -
            record.rc_pressure_response + record.pressure_relaxation_split +
            record.simplec_extra_flux)-record.conservative_flux;
        if (record.neighbour>=0 && independent_pressure_operator) {
            record.internal_pressure_operator=(*independent_pressure_operator)(f);
            record.pressure_operator_error=(record.predictor_hbya_flux -
                record.rc_full_flux) - record.internal_pressure_operator;
            if (!std::isfinite(record.pressure_operator_error))
                throw std::domain_error("same-state momentum audit: invalid RC operator");
            out.max_pressure_operator_error=std::max(out.max_pressure_operator_error,
                std::abs(record.pressure_operator_error));
        }
        if (!std::isfinite(record.deferred_tvd_flux) ||
            !std::isfinite(record.decomposition_error) ||
            !std::isfinite(record.rc_pressure_response))
            throw std::domain_error("same-state momentum audit: nonfinite face");
        out.max_decomposition_error=std::max(out.max_decomposition_error,
            std::abs(record.decomposition_error));
        if (std::abs(record.deferred_tvd_flux)>out.max_deferred_tvd_flux) {
            out.max_deferred_tvd_flux=std::abs(record.deferred_tvd_flux);
            out.max_deferred_tvd_face=f;
        }
        out.faces.push_back(record);
    }
    return out;
}


def graded(n: int, grading: float | tuple[tuple[float, float, float], ...]) -> np.ndarray:
    """Return N+1 monotone edge locations, with multigrading subsegments.

    Each segment uses its relative physical length, cell allocation and
    (last/first cell size) ratio. Counts are assigned by largest remainder.
    This is a reproducible, independent approximation to blockMesh grading.
    """
    if n < 1:
        raise ValueError('positive edge cell count required')
    segments = grading if isinstance(grading, tuple) else ((1., 1., grading),)
    if any(not all(math.isfinite(float(v)) and float(v) > 0 for v in s) for s in segments):
        raise ValueError('grading fractions and ratios must be finite and positive')
    if len(segments) > n:
        raise ValueError('insufficient cells for multigrading subsegments')
    fractions = np.array([s[1] for s in segments], dtype=float)
    quotas = (n - len(segments)) * fractions / fractions.sum()
    extras = np.floor(quotas).astype(int)
    order = np.argsort(-(quotas - extras), kind='stable')
    extras[order[:n - len(segments) - int(extras.sum())]] += 1
    counts = extras + 1
    lengths = np.array([s[0] for s in segments], dtype=float)
    lengths /= lengths.sum()
    edges = [0.]
    base = 0.
    for length, (_, _, ratio), count in zip(lengths, segments, counts):
        if count == 1 or math.isclose(ratio, 1.):
            local = np.linspace(0., 1., count + 1)
        else:
            logq = math.log(ratio) / (count - 1)
            local = np.expm1(np.arange(count + 1) * logq) / math.expm1(count * logq)
        edges.extend((base + length * local[1:]).tolist())
        base += length
    result = np.asarray(edges, dtype=np.float64)
    result[-1] = 1.
    if len(result) != n + 1 or not np.all(np.diff(result) > 0):
        raise ValueError('degenerate grading')
    return result


def block_specs(resolution: str) -> list[dict]:
    if resolution not in ('smoke', 'coarse', 'medium', 'full'):
        raise ValueError('resolution must be smoke, coarse, medium or full')
    # All blocks sharing a geometric edge retain identical sampling counts.
    factors = {'smoke': .12, 'coarse': .25, 'medium': .5, 'full': 1.}[resolution]
    nx0 = max(2, round(2 * factors))
    nx1 = max(8, round(88 * factors))
    nx2 = max(12, round(97 * factors))
    nx3 = max(6, round(33 * factors))
    ny_upper = max(16, round(65 * factors))
    ny_lower = max(12, round(48 * factors))
    # x0,x1,ybottom-left,ytop-left,ybottom-right,ytop-right, nx, ny, xgrading, yl,yr
    return [
        dict(x0=-130, x1=-110, ybl=1, ytl=9, ybr=1, ytr=9,
             nx=nx0, ny=ny_upper, gx=.3, yl=Y_SPACING, yr=Y_SPACING),
        dict(x0=-110, x1=0, ybl=1, ytl=9, ybr=1, ytr=9,
             nx=nx1, ny=ny_upper, gx=((106, 63, .1), (4, 25, .3)),
             yl=Y_SPACING, yr=Y_SPACING),
        dict(x0=0, x1=8, ybl=0, ytl=1, ybr=0, ytr=1,
             nx=nx2, ny=ny_lower, gx=1., yl=Y_WALL, yr=Y_LOWER1),
        dict(x0=8, x1=50, ybl=0, ytl=1, ybr=0, ytr=3.125,
             nx=nx3, ny=ny_lower, gx=80., yl=Y_LOWER1, yr=Y_LOWER2),
        dict(x0=0, x1=8, ybl=1, ytl=9, ybr=1, ytr=9,
             nx=nx2, ny=ny_upper, gx=1., yl=Y_SPACING, yr=Y_UPPER1),
        dict(x0=8, x1=50, ybl=1, ytl=9, ybr=3.125, ytr=9,
             nx=nx3, ny=ny_upper, gx=80., yl=Y_UPPER1, yr=Y_SPACING2),
    ]


def make_structured_mesh(resolution: str) -> dict:
    specs = block_specs(resolution)
    points: list[tuple[float, float, float]] = []
    point_map: dict[tuple[float, float, float], int] = {}
    faces: list[tuple[int, ...]] = []
    owners: list[int] = []
    neighbours: list[int] = []
    face_map: dict[tuple[int, ...], int] = {}
    cell_faces: list[list[int]] = []
    min_positive_area = float('inf')

    def pid(x: float, y: float, z: float) -> int:
        key = (round(x, 11), round(y, 11), round(z, 11))
        if key not in point_map:
            point_map[key] = len(points)
            points.append(tuple(H * c for c in key))
        return point_map[key]

    def add_face(vertices: tuple[int, ...], owner: int) -> int:
        key = tuple(sorted(vertices))
        found = face_map.get(key)
        if found is not None:
            if neighbours[found] >= 0:
                raise ValueError('nonmanifold interface across blocks')
            neighbours[found] = owner
            return found
        fid = len(faces)
        face_map[key] = fid
        faces.append(vertices)
        owners.append(owner)
        neighbours.append(-1)
        return fid

    for block in specs:
        xs = graded(block['nx'], block['gx'])
        left = graded(block['ny'], block['yl'])
        right = graded(block['ny'], block['yr'])
        ids = np.zeros((block['ny'] + 1, block['nx'] + 1, 2), dtype=np.int64)
        coords = np.zeros((block['ny'] + 1, block['nx'] + 1, 2), dtype=float)
        for j in range(block['ny'] + 1):
            for i, s in enumerate(xs):
                x = block['x0'] + s * (block['x1'] - block['x0'])
                yl = block['ybl'] + left[j] * (block['ytl'] - block['ybl'])
                yr = block['ybr'] + right[j] * (block['ytr'] - block['ybr'])
                y = (1. - s) * yl + s * yr
                coords[j, i] = (x, y)
                for k in (0, 1):
                    ids[j, i, k] = pid(x, y, k)
        for j in range(block['ny']):
            for i in range(block['nx']):
                p00, p10, p11, p01 = (
                    coords[j, i], coords[j, i+1], coords[j+1, i+1], coords[j+1, i]
                )
                area = .5 * (
                    p00[0]*p10[1] - p10[0]*p00[1]
                    + p10[0]*p11[1] - p11[0]*p10[1]
                    + p11[0]*p01[1] - p01[0]*p11[1]
                    + p01[0]*p00[1] - p00[0]*p01[1]
                ) * H**2
                if not math.isfinite(area) or area <= 1.e-17:
                    raise ValueError(f'degenerate block {resolution} cell area={area}')
                min_positive_area = min(min_positive_area, area)
                a,b,c,d = (int(ids[j,i,0]), int(ids[j,i+1,0]),
                           int(ids[j+1,i+1,0]), int(ids[j+1,i,0]))
                e,f,g,h = (int(ids[j,i,1]), int(ids[j,i+1,1]),
                           int(ids[j+1,i+1,1]), int(ids[j+1,i,1]))
                ci = len(cell_faces)
                cell_faces.append([
                    add_face((a,d,c,b), ci), add_face((e,f,g,h), ci),
                    add_face((a,b,f,e), ci), add_face((d,h,g,c), ci),
                    add_face((a,e,h,d), ci), add_face((b,c,g,f), ci),
                ])

    positions = np.asarray(points, dtype=np.float64)
    patches = {p: [] for p in PATCH_TYPES}
    tol = 1.e-8
    for fid, vertex_ids in enumerate(faces):
        if neighbours[fid] >= 0:
            continue
        x,y,z = positions[np.asarray(vertex_ids), :].mean(axis=0) / H
        if abs(z) <= tol:
            patch = 'front'
        elif abs(z - 1) <= tol:
            patch = 'back'
        elif abs(x + 130) <= tol:
            patch = 'inlet'
        elif abs(x - 50) <= tol:
            patch = 'outlet'
        elif abs(y - 9) <= tol:
            patch = 'upperWallStartup' if x < -110 else 'upperWall'
        elif abs(y - 1) <= tol and x < 0:
            patch = 'lowerWallStartup' if x < -110 else 'lowerWall'
        elif abs(x) <= tol and y < 1:
            patch = 'lowerWall'
        elif abs(y) <= tol and x > 0:
            patch = 'lowerWall'
        else:
            raise ValueError(f'unclassified blockMesh face {fid} at x/h={x},y/h={y},z/h={z}')
        patches[patch].append(fid)
    if any(not fs for fs in patches.values()):
        raise ValueError('a required OpenFOAM physical patch is empty')
    if sum(map(len, patches.values())) != sum(nb < 0 for nb in neighbours):
        raise ValueError('incomplete boundary coverage')

    face_offsets = np.zeros(len(faces)+1, dtype=np.uint64)
    for f, vertices in enumerate(faces):
        face_offsets[f+1] = face_offsets[f] + len(vertices)
    cell_offsets = np.zeros(len(cell_faces)+1, dtype=np.uint64)
    for c, fids in enumerate(cell_faces):
        cell_offsets[c+1] = cell_offsets[c] + len(fids)
    return {
        'points': positions,
        'face_vertices': np.fromiter((v for face in faces for v in face), dtype=np.uint64),
        'face_offsets': face_offsets,
        'owner': np.asarray(owners, dtype=np.uint64),
        'neighbour': np.asarray(neighbours, dtype=np.int64),
        'cell_faces': np.fromiter((v for face in cell_faces for v in face), dtype=np.uint64),
        'cell_offsets': cell_offsets,
        'n_points': len(points), 'n_faces': len(faces), 'n_cells': len(cell_faces),
        'boundary_patch_assignment': [
            {'name': name, 'type': kind, 'face_ids': patches[name]}
            for name, kind in PATCH_TYPES.items()
        ],
        'minimum_cell_area_m2': min_positive_area,
    }


def load_openfoam_polymesh(case: Path) -> dict:
    """Import *actual* OpenFOAM ASCII polyMesh, preserving all CSR connections."""
    from cfdx.io.adapters.openfoam import OpenFOAMAdapter
    root = case / 'constant' / 'polyMesh'
    if not root.is_dir():
        raise ValueError(f'OpenFOAM ASCII polyMesh not found at {root}')
    reader = OpenFOAMAdapter()
    points, cells = reader._parse_mesh(root)
    if points is None or cells is None:
        raise ValueError(f'OpenFOAM mesh parse failed: {reader._mesh_parse_error}')
    mesh = cells['cfdx_csr']
    names = {p['name']: p['type'].lower() for p in mesh['boundary_patch_assignment']}
    expected = {name: kind.lower() for name, kind in PATCH_TYPES.items()}
    if set(names) != set(expected):
        raise ValueError(f'unexpected OpenFOAM patch names/types: {names}')
    for entry in mesh['boundary_patch_assignment']:
        name = entry['name']
        kind = entry['type'].lower()
        # OpenFOAM represents inlet and outlet as a generic patch; CFDX's
        # typed topology must use INLET/OUTLET, not UNKNOWN or WALL.
        if name in ('inlet', 'outlet') and kind == 'patch':
            entry['type'] = name
        elif kind != expected[name]:
            raise ValueError(f'unexpected OpenFOAM type {kind} for {name}')
    bounds_min = np.min(points, axis=0) / H
    bounds_max = np.max(points, axis=0) / H
    if not np.allclose(bounds_min, [-130, 0, 0], atol=1e-5) or not np.allclose(
            bounds_max, [50, 9, 1], atol=1e-5):
        raise ValueError(f'polyMesh domain does not match OpenFOAM BFS: {bounds_min}, {bounds_max}')
    return mesh


def make_case_setup(max_iterations: int, alpha_u: float, alpha_p: float,
                    pressure_restart: int = 160,
                    pressure_scaling: str = 'none',
                    pressure_krylov: str = 'auto',
                    pressure_preconditioner: str = 'auto',
                    pressure_tolerance: float = 1.e-11,
                    inlet_omega: float = OMEGA_IN,
                    initial_omega: float = OMEGA_INITIAL,
                    sst_newton_sink: bool = False,
                    sst_omega_first: bool = False,
                    sst_wall_factor: int = 6,
                    sst_inner_iterations: int = 800, *,
                    sst_provisional: bool = False,
                    sst_picard_damping: float = 1.0,
                    sst_relative_gate: bool = False,
                    sst_compensated_gate: bool = False,
                    sst_nonlinear_line_search: bool = False,
                    sst_linear_relaxation: float = 0.7,
                    sst_molecular_wall_diffusion: bool = False,
                    v17_pressure_line_search: bool = False,

                    v17_flux_audit: bool = False,
                    v17_pseudo_momentum: bool = False,
                    v17_initial_cfl: float = 0.3,
                    v17_min_cfl: float = 0.03,
                    v17_max_cfl: float = 3.0,
                    v18_full_flux_pressure_oracle: bool = False,
                    v18_sparse_flux_pressure_jacobian: bool = False,
                    v19_full_pressure_flux_step: bool = False,
                    v21_adaptive_relaxation: bool = False,
                    convection_scheme: str = 'upwind', pressure_refinement_steps: int = 0) -> CaseSetup:
    convection_keys = {
        'upwind': 'numerics.convection.upwind',
        'second_order_upwind': 'numerics.convection.second_order_upwind',
        'tvd_minmod': 'numerics.convection.tvd.minmod',
    }
    if convection_scheme not in convection_keys:
        raise ValueError('unsupported TH-03 convection scheme')
    if (not 1 <= pressure_restart <= 2048 or
            pressure_scaling not in ('none', 'row_column', 'symmetric_diagonal')):
        raise ValueError('invalid pressure Krylov controls')
    if not (math.isfinite(pressure_tolerance) and pressure_tolerance > 0):
        raise ValueError('invalid pressure tolerance')
    if not isinstance(sst_inner_iterations,int) or sst_inner_iterations <= 0:
        raise ValueError('SST inner iterations must be a positive integer')
    if v19_full_pressure_flux_step and not (v18_sparse_flux_pressure_jacobian or v18_full_flux_pressure_oracle):
        raise ValueError('V19 full flux requires a V18 complete Jacobian')
    if v19_full_pressure_flux_step and v17_pressure_line_search:
        raise ValueError('V19 full flux and pressure line search are exclusive')
    if v21_adaptive_relaxation and not v19_full_pressure_flux_step:
        raise ValueError('V21 adaptive relaxation requires V19 full flux step')
    if sst_wall_factor not in (6, 60):
        raise ValueError('SST wall factor must be 6 or 60')
    if not (math.isfinite(sst_picard_damping) and 0.0 < sst_picard_damping <= 1.0):
        raise ValueError('SST Picard damping must be finite and in (0, 1]')
    if (not all(map(math.isfinite,(v17_initial_cfl,v17_min_cfl,v17_max_cfl))) or
            not 0.0 < v17_min_cfl <= v17_initial_cfl <= v17_max_cfl):
        raise ValueError('V17 pseudo CFL bounds must be finite and ordered')
    if not (math.isfinite(sst_linear_relaxation) and 0.0 < sst_linear_relaxation <= 1.0):
        raise ValueError('SST scalar linear relaxation must be finite and in (0,1]')
    if sst_nonlinear_line_search and sst_picard_damping != 1.0:
        raise ValueError('SST nonlinear line search and fixed Picard damping are exclusive')
    if not all(math.isfinite(v) and v > 0 for v in (inlet_omega, initial_omega)):
        raise ValueError('inlet and initial omega must be finite and strictly positive')
    if max_iterations <= 0 or not (0. < alpha_u <= 1. and 0. < alpha_p <= 1.):
        raise ValueError('invalid numerical controls')
    setup = CaseSetup(source=SourceInfo(solver='OpenFOAM', version='v2606',
        case_name='backwardFacingStep2D', format='openfoam-blockmesh-sourced'))
    setup.physics_model = 'incompressible_laminar'  # experimental SST opt-in
    setup.turbulence_model = 'k_omega_sst'
    setup.energy_model = 'isothermal'
    setup.solver_mode = 'steady'
    setup.units = 'SI'
    setup.materials = [MaterialSpec(name='air', density=RHO,
        dynamic_viscosity=RHO * NU, turbulence_model='k_omega_sst')]
    bcs = []
    for name, kind in PATCH_TYPES.items():
        scalar_types = (
            (SSTScalarBoundaryType.FIXED_VALUE, SSTScalarBoundaryType.FIXED_VALUE)
            if name == 'inlet' else
            (SSTScalarBoundaryType.WALL_K_ZERO, SSTScalarBoundaryType.WALL_OMEGA_SST)
            if kind == 'wall' else
            (SSTScalarBoundaryType.ZERO_GRADIENT, SSTScalarBoundaryType.ZERO_GRADIENT)
        )
        scalar = [SSTScalarBoundarySpec(field='k', type=scalar_types[0],
            value=K_IN if name == 'inlet' else 0.),
            SSTScalarBoundarySpec(field='omega', type=scalar_types[1],
            value=inlet_omega if name == 'inlet' else 0.)]
        if name == 'inlet':
            bc = BoundarySpec(patch_name=name, type=BCType.INLET,
                value_type=BCValueType.FIXED,
                velocity_vector=[VELOCITY, 0., 0.], velocity_magnitude=VELOCITY,
                turbulence_intensity=math.sqrt(K_IN / (1.5 * VELOCITY**2)),
                turbulence_length_scale=math.sqrt(K_IN) / (.09**.25 * inlet_omega),
                sst_scalar_conditions=scalar)
        elif name == 'outlet':
            bc = BoundarySpec(patch_name=name, type=BCType.OUTLET,
                value_type=BCValueType.OUTLET_PRESSURE, pressure=0.,
                sst_scalar_conditions=scalar)
        elif kind == 'wall':
            bc = BoundarySpec(patch_name=name, type=BCType.WALL,
                value_type=BCValueType.WALL_NO_SLIP,
                velocity_vector=[0., 0., 0.], sst_scalar_conditions=scalar)
        else:
            bc = BoundarySpec(patch_name=name,
                type=BCType.SYMMETRY if kind == 'symmetryPlane' else BCType.EMPTY,
                value_type=BCValueType.ZERO_GRADIENT,
                sst_scalar_conditions=scalar)
        bcs.append(bc)
    setup.boundary_conditions = bcs
    setup.initial_condition = InitialCondition(velocity=VELOCITY,
        velocity_vector=[VELOCITY,0.,0.], pressure=0.,
        scalar_fields={'k': K_IN, 'omega': initial_omega})
    setup.numerics.max_iterations = max_iterations
    setup.numerics.under_relaxation_momentum = alpha_u
    setup.numerics.under_relaxation_pressure = alpha_p
    setup.numerics.raw_settings['sst_transport_max_iterations'] = str(sst_inner_iterations)
    setup.numerics.raw_settings['sst_scale_aware_convergence'] = str(bool(sst_relative_gate)).lower()
    setup.numerics.raw_settings['sst_omega_newton_sink'] = str(bool(sst_newton_sink)).lower()
    setup.numerics.raw_settings['sst_sequential_omega_first'] = str(bool(sst_omega_first)).lower()
    setup.numerics.raw_settings['sst_wall_omega_factor'] = str(sst_wall_factor)
    setup.numerics.raw_settings['sst_compensated_residual_gate'] = str(bool(sst_compensated_gate)).lower()
    setup.numerics.raw_settings['sst_nonlinear_line_search'] = str(bool(sst_nonlinear_line_search)).lower()
    setup.numerics.raw_settings['sst_transport_linear_relaxation'] = str(sst_linear_relaxation)
    setup.numerics.raw_settings['sst_molecular_wall_diffusion'] = str(bool(sst_molecular_wall_diffusion)).lower()
    setup.numerics.raw_settings['v17_pressure_line_search'] = str(bool(v17_pressure_line_search)).lower()
    setup.numerics.raw_settings['v17_flux_patch_audit'] = str(bool(v17_flux_audit)).lower()
    setup.numerics.raw_settings['v18_full_flux_pressure_oracle'] = str(bool(v18_full_flux_pressure_oracle)).lower()
    setup.numerics.raw_settings['v18_sparse_flux_pressure_jacobian'] = str(bool(v18_sparse_flux_pressure_jacobian)).lower()
    setup.numerics.raw_settings['v19_full_pressure_flux_step'] = str(bool(v19_full_pressure_flux_step)).lower()
    setup.numerics.raw_settings['v21_adaptive_relaxation'] = str(bool(v21_adaptive_relaxation)).lower()
    setup.numerics.raw_settings['v17_pseudo_momentum'] = str(bool(v17_pseudo_momentum)).lower()
    setup.numerics.raw_settings['v17_pseudo_initial_cfl'] = str(v17_initial_cfl)
    setup.numerics.raw_settings['v17_pseudo_min_cfl'] = str(v17_min_cfl)
    setup.numerics.raw_settings['v17_pseudo_max_cfl'] = str(v17_max_cfl)
    # Provisional steps are NOT certified; the final coupled convergence gate
    # continues to require converged SST, carrier equations and conservation.
    if sst_provisional:
        setup.numerics.raw_settings['sst_outer_provisional'] = 'enabled'
    if sst_picard_damping != 1.0:
        setup.numerics.raw_settings['sst_picard_damping'] = str(sst_picard_damping)
    setup.numerics.raw_settings['pressure_gmres_restart'] = str(pressure_restart)
    setup.numerics.raw_settings['pressure_linear_scaling'] = pressure_scaling
    setup.numerics.raw_settings['pressure_krylov'] = pressure_krylov
    setup.numerics.raw_settings['pressure_preconditioner'] = pressure_preconditioner
    setup.numerics.raw_settings['pressure_linear_tolerance'] = str(pressure_tolerance)
    if not isinstance(pressure_refinement_steps, int) or not 0 <= pressure_refinement_steps <= 8:
        raise ValueError('pressure refinement steps must be an integer in [0,8]')
    if pressure_refinement_steps:
        setup.numerics.raw_settings['pressure_iterative_refinement_steps'] = str(pressure_refinement_steps)
    setup.numerics.raw_settings['pressure_face_interpolation'] = 'arithmetic'
    setup.numerics.selection = NumericalSelectionConfig(entries=[
        NumericalSelection(family='gradient', configuration_key='numerics.gradient.gauss'),
        NumericalSelection(family='convection', configuration_key=convection_keys[convection_scheme]),
        NumericalSelection(family='pressure_velocity', configuration_key='pressure_velocity.simple'),
        NumericalSelection(family='linear_solver', configuration_key='linear.fgmres'),
    ], required_families=['gradient', 'convection', 'pressure_velocity'])
    return setup


def count_invalid_extrusion_patch_faces(mesh: dict) -> int:
    """Check actual polygon geometry against the TH-03 2-D patch contract.

    Share the *same* geometry gate between the independent mesh audit and the
    case writer.  Do not infer an EMPTY cap from a face's first edge or centre.
    """
    points = np.asarray(mesh['points'], dtype=float)
    offsets = np.asarray(mesh['face_offsets'], dtype=np.int64)
    vertices = np.asarray(mesh['face_vertices'], dtype=np.int64)
    nf = int(mesh['n_faces'])
    invalid = 0
    for patch in mesh['boundary_patch_assignment']:
        name = patch['name']
        if name not in PATCH_TYPES:
            continue
        expects_cap = PATCH_TYPES[name].lower() == 'empty'
        for face in patch['face_ids']:
            f = int(face)
            if not 0 <= f < nf:
                invalid += 1
                continue
            face_vertices = vertices[offsets[f]:offsets[f+1]]
            if (face_vertices.size < 3 or np.any(face_vertices < 0) or
                    np.any(face_vertices >= len(points))):
                invalid += 1
                continue
            z = points[face_vertices, 2]
            cap = float(np.ptp(z)) <= 1e-10 * H
            on_declared_plane = cap and (
                abs(float(z[0])) <= 1e-10 * H if name == 'front' else
                abs(float(z[0] - H)) <= 1e-10 * H if name == 'back' else False
            )
            if (expects_cap and not on_declared_plane) or (not expects_cap and cap):
                invalid += 1
    return invalid


def write_case(path: Path, mesh: dict, *, mesh_source: str,
               max_iterations: int = 100, alpha_u: float = .25,
               alpha_p: float = .1, pressure_restart: int = 160,
               pressure_scaling: str = 'none',
               pressure_krylov: str = 'auto',
               pressure_preconditioner: str = 'auto',
               pressure_tolerance: float = 1.e-11,
               inlet_omega: float = OMEGA_IN,
               initial_omega: float = OMEGA_INITIAL,
               sst_newton_sink: bool = False,
               sst_omega_first: bool = False,
               sst_wall_factor: int = 6,
               sst_inner_iterations: int = 800,
               sst_provisional: bool = False,
               sst_picard_damping: float = 1.0,
               sst_relative_gate: bool = False,
               sst_compensated_gate: bool = False,
               sst_nonlinear_line_search: bool = False,
               sst_linear_relaxation: float = 0.7,
               sst_molecular_wall_diffusion: bool = False,
               v17_pressure_line_search: bool = False,

               v17_flux_audit: bool = False,
               v17_pseudo_momentum: bool = False,
               v17_initial_cfl: float = 0.3,
               v17_min_cfl: float = 0.03,
               v17_max_cfl: float = 3.0,
               v18_full_flux_pressure_oracle: bool = False,
               v18_sparse_flux_pressure_jacobian: bool = False,
                    v19_full_pressure_flux_step: bool = False,
               v21_adaptive_relaxation: bool = False,
               convection_scheme: str = 'upwind', pressure_refinement_steps: int = 0) -> dict:
    # A mislabeled lateral wall must never reach the CFDX solver as EMPTY.
    # Audit and case writer intentionally use this single geometry contract.
    if count_invalid_extrusion_patch_faces(mesh):
        raise ValueError('TH-03 EMPTY/wall patch geometry is inconsistent')
    path.parent.mkdir(parents=True, exist_ok=True)
    setup = make_case_setup(max_iterations, alpha_u, alpha_p,
                            pressure_restart, pressure_scaling, pressure_krylov,
                            pressure_preconditioner, pressure_tolerance,
                            inlet_omega, initial_omega,
                            sst_newton_sink, sst_omega_first, sst_wall_factor,
                            sst_inner_iterations, sst_provisional=sst_provisional,
                            sst_picard_damping=sst_picard_damping,
                            sst_relative_gate=sst_relative_gate,
                            sst_compensated_gate=sst_compensated_gate,
                            sst_nonlinear_line_search=sst_nonlinear_line_search,
                            sst_linear_relaxation=sst_linear_relaxation,
                            sst_molecular_wall_diffusion=sst_molecular_wall_diffusion,
                            v17_pressure_line_search=v17_pressure_line_search,
                            v17_flux_audit=v17_flux_audit,
                            v17_pseudo_momentum=v17_pseudo_momentum,
                            v17_initial_cfl=v17_initial_cfl,
                            v17_min_cfl=v17_min_cfl,
                            v17_max_cfl=v17_max_cfl,
                            v18_full_flux_pressure_oracle=v18_full_flux_pressure_oracle,
                            v18_sparse_flux_pressure_jacobian=v18_sparse_flux_pressure_jacobian,
                            v19_full_pressure_flux_step=v19_full_pressure_flux_step,
                            v21_adaptive_relaxation=v21_adaptive_relaxation,
                            convection_scheme=convection_scheme,
                            pressure_refinement_steps=pressure_refinement_steps)
    setup.source.case_path = mesh_source
    setup.source_metadata['physical_qualification'] = 'NOT_QUALIFIED'
    setup.source_metadata['inlet_omega_origin'] = (
        'derived from OpenFOAM documented inlet nut/nu=0.009; '
        '0.orig/omega has not been byte-verified')
    setup.source_metadata['initial_omega_must_not_be_assumed_inlet'] = 'true'
    setup.source_metadata['inlet_eddy_viscosity_ratio'] = str(K_IN / (NU * inlet_omega))
    setup.source_metadata['mesh_description'] = mesh_source
    setup.source_metadata['physics_gaps'] = (
        'RANS-SST experimental; wall model not equivalent to OpenFOAM; '
        'first-order convection; not grid-converged; no verified Cf/Cp/profiles'
    )
    topology_hash, geometry_hash, mesh_hash = _integrity_hashes(mesh)
    metadata, face_ids, face_offsets = _boundary_patch_metadata(mesh)
    if metadata is None:
        raise ValueError('no boundary metadata for CFDX solver')
    with h5py.File(path, 'w') as h:
        for name, value in {
            'format': 'CFDX-HDF5-mesh-v1', 'format_version': '1',
            'schema_version': '1', 'cfdx_version': '0.7',
            'mesh_topology': 'cfdx-csr-v1',
            'n_points': str(mesh['n_points']), 'n_faces': str(mesh['n_faces']),
            'n_cells': str(mesh['n_cells']),
            'topology_hash': topology_hash, 'geometry_hash': geometry_hash,
            'mesh_hash': mesh_hash, 'boundary_patches': metadata,
            'source_solver': 'OpenFOAM', 'source_format': 'openfoam',
            'source_version': 'v2606', 'source_case_path': mesh_source,
            'source_case_name': 'backwardFacingStep2D',
            'case_setup_json': json.dumps(setup.model_dump(mode='json')),
        }.items():
            h.attrs[name] = value
        for key in ('points','face_vertices','face_offsets','owner','neighbour',
                    'cell_faces','cell_offsets'):
            h.create_dataset(key, data=mesh[key], compression='gzip', compression_opts=2)
        h.create_dataset('patch_face_ids', data=face_ids)
        h.create_dataset('patch_face_offsets', data=face_offsets)
    return {'case': str(path), 'cells': mesh['n_cells'], 'faces': mesh['n_faces'],
        'patch_faces': {p['name']: len(p['face_ids'])
                        for p in mesh['boundary_patch_assignment']},
        'source_mesh': mesh_source,
        'momentum_convection_scheme': setup.numerics.selection.entries[1].configuration_key,
        'pressure_gmres_restart': pressure_restart,
        'pressure_linear_scaling': pressure_scaling,
        'pressure_krylov': pressure_krylov,
        'pressure_preconditioner': pressure_preconditioner,
        'pressure_linear_tolerance': pressure_tolerance,
        'reynolds_h': VELOCITY*H/NU,
        'inlet_omega_s_inverse': inlet_omega,
        'initial_omega_s_inverse': initial_omega,
        'inlet_nut_over_nu': K_IN / (NU * inlet_omega),
        'reference_reattachment_x_over_h': {
            'value': 6.26, 'experimental_sigma': .10,
            'directly_comparable': False,
            'reason': 'OpenFOAM surrogate Re_h~35983 differs from frozen TH-03 experimental Re_h=37500 and inlet-profile contract',
        },
        'qualification': 'NOT_QUALIFIED',
        'warnings': ['TH-03 experimental registry Re_h=37500 differs from OpenFOAM nominal Re_h=36000',
                     'experimental SST opt-in', 'CFDX first-order upwind',
                     'wall treatment not equivalent to OpenFOAM tutorial',
                     'OpenFOAM omega inlet is derived from published nut/nu, not verified from raw file',
                     'initial profile and grid convergence not verified'],
    }



"""Build a CFDX TH-03 case with the six-block OpenFOAM BFS geometry.

Geometry, block counts, edge-grading and physical inlet values are transcribed
from the publicly documented OpenFOAM v2606 backwardFacingStep2D tutorial:
https://gitlab.com/openfoam/core/openfoam/-/raw/OpenFOAM-v2606/tutorials/incompressible/simpleFoam/backwardFacingStep2D/system/blockMeshDict

The structured discretisation uses a documented transfinite bilinear mapping
and independent piecewise geometric edge grading. It is NOT a byte-exact
OpenFOAM blockMesh output. For exact native topology, use --openfoam-case with
ASCII constant/polyMesh generated by the actual OpenFOAM blockMesh utility.

All results remain diagnostic until the true physical/numerical qualification
criteria are met. The OpenFOAM tutorial uses a different velocity convection
scheme and wall functions; numerical equivalence is not assumed.
"""

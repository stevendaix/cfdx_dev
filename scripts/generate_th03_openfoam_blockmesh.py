H = 0.0127
VELOCITY = 44.2
NU = 1.56e-5
RHO = 1.2
K_IN = 1.09e-3
# The documented OpenFOAM *inlet* condition targets nut/nu = 0.009.
# The previous 181728 s^-1 was applied to both inlet and initial state,
# yielding nut/nu = 3.84e-4 for the specified k and nu: 23.4x too small.
